namespace SkyFireLauncher.Realm;

// A handful of small, targeted byte patches to the client's login flow.
// Each pattern/replacement pair was matched against the disassembly to
// confirm what it actually does before including it here - in particular,
// "Email" (the one that matters for connection mode) overwrites a single
// conditional-jump opcode (0x74, JZ) with an unconditional jump (0xEB)
// right at the branch that otherwise routes login through the modern
// Battle.net/Agent protocol - forcing the classic realmList-based path
// instead, which is what SkyFire's authserver actually speaks.
//
// That jump is often already patched on disk. 0x00 in the generic patterns
// below is a wildcard, so Email cannot use that matcher: it also hits an
// unrelated 0x0C. Find the unique suffix after the JZ/JMP and write 0x74
// (BattlenetLogin) or 0xEB (GruntLogin).
//
// 0x00 bytes in a pattern are wildcards (match any byte). A match is
// replaced starting at its own offset - shorter replacements just
// overwrite the leading bytes and leave the rest of the match untouched.
public static class LoginFlowPatches
{
    public static readonly (string Name, byte[] Pattern, byte[] Replacement)[] X64 =
    [
        ("Send", [0x44, 0x00, 0x44, 0x24, 0x50, 0x89, 0x00, 0x1C, 0x41, 0x00, 0xC0, 0x25, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00],
                 [0x45, 0x31, 0xC0, 0x90, 0x90]),
        ("User", [0x40, 0x00, 0x00, 0x00, 0x48, 0x8B, 0xCF, 0xE8, 0x00, 0x00, 0x00, 0x00, 0x48, 0x85, 0xC0, 0x75, 0x00, 0x48, 0x8D],
                 [0x00]),
        ("RaF", [0xE8, 0x00, 0x00, 0x00, 0x00, 0x84, 0xC0, 0x74, 0x00, 0x48, 0x8D, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0xE8, 0x00, 0x00, 0x00, 0x00, 0x8B],
                 [0x90, 0x90, 0x90, 0x90, 0x90]),
        ("Rcv", [0x01, 0x0F, 0x85, 0x00, 0x00, 0x00, 0x00, 0x49, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x4D, 0x00, 0x00, 0x4C, 0x00, 0x00],
                [0xFF, 0x0F, 0x84]),
    ];

    public static readonly (string Name, byte[] Pattern, byte[] Replacement)[] X86 =
    [
        ("Send", [0x8B, 0x00, 0x00, 0x8B, 0x00, 0x81, 0x00, 0x48, 0x01],
                 [0x33, 0xC0, 0x90]),
        ("User", [0x40, 0x00, 0xE8, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x85, 0xC0, 0x75],
                 [0x00]),
        ("RaF", [0xE8, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x84, 0xC0, 0x74, 0x00, 0x8D, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0xE8, 0x00, 0x00, 0x00, 0x00, 0xFF, 0xB5, 0x00, 0x00, 0x00, 0x00, 0x8D],
                 [0x90, 0x90, 0x90, 0x90, 0x90]),
        ("Rcv", [0x01, 0x0F, 0x85, 0x00, 0x00, 0x00, 0x00, 0xFF, 0x75, 0x14, 0x8B, 0x8B, 0x50, 0x45, 0x00, 0x00, 0xFF, 0x75, 0x10, 0x53, 0xFF, 0x75, 0x08, 0x6A, 0x17],
                [0xFF, 0x0F, 0x84]),
    ];

    // Bytes immediately after the Email JZ/JMP on 5.4.8 Wow-64. Exact match
    // (zeros are zeros). The old wildcard pattern also hits an unrelated 0x0C.
    private static readonly byte[] X64EmailSuffix =
        [0x05, 0xBB, 0x01, 0x00, 0x00, 0x00, 0x48, 0x85, 0xC9, 0x74, 0x5D, 0x48, 0x8B, 0x01, 0xFF, 0x90];

    public static byte[] EmailOpcode(bool enableAuthnetLogin) =>
        enableAuthnetLogin ? [0x74] : [0xEB];

    public static bool TryFindEmailOpcode(byte[] haystack, bool is64Bit, out int opcodeOffset)
    {
        opcodeOffset = -1;
        if (!is64Bit)
            return false;

        var suffix = X64EmailSuffix;
        var last = haystack.Length - 1 - suffix.Length;
        for (var i = 0; i <= last; i++)
        {
            var opcode = haystack[i];
            if (opcode != 0x74 && opcode != 0xEB)
                continue;

            var matched = true;
            for (var j = 0; j < suffix.Length; j++)
            {
                if (haystack[i + 1 + j] != suffix[j])
                {
                    matched = false;
                    break;
                }
            }

            if (!matched)
                continue;

            opcodeOffset = i;
            return true;
        }

        return false;
    }
}
